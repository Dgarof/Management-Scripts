    if ([string]::IsNullOrWhiteSpace($cmbRoomList.Text))
    {
        return
    }

    $Members = Get-DistributionGroupMember `
        -Identity $cmbRoomList.Text `
        -ErrorAction SilentlyContinue |
        Sort-Object DisplayName

    foreach($Member in $Members)
    {
        # $lstMembers.Items.Add($Member.DisplayName)
        [void]$lstMembers.Items.Add($Member.DisplayName)
    }
}
function New-LectraRoomMailbox {

    $RoomName = $txtRoomName.Text.Trim()
    $Country  = $cmbCountry.Text.Trim()
    $City     = $cmbCity.Text.Trim()
    $Building = $txtBuilding.Text.Trim()
    $Floor    = $cmbFloor.Text.Trim()
    $Capacity = $txtCapacity.Text.Trim()
    $Domain   = $cmbDomain.Text.Trim()

    # Contrôles obligatoires

    if ([string]::IsNullOrWhiteSpace($RoomName))
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Nom de salle obligatoire."
        )
        return
    }

    if ([string]::IsNullOrWhiteSpace($Country))
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Pays obligatoire."
        )
        return
    }

    if ([string]::IsNullOrWhiteSpace($City))
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Ville obligatoire."
        )
        return
    }

    if ([string]::IsNullOrWhiteSpace($Domain))
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Domaine SMTP obligatoire."
        )
        return
    }

    if ([string]::IsNullOrWhiteSpace($Floor))
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Sélectionnez un étage."
        )
        return
    }

    # Traduction étage -> entier Exchange

    switch ($Floor)
    {
        "Sous-sol" { $FloorNumber = -1 }
        "RDC"      { $FloorNumber = 0 }
        default    { $FloorNumber = [int]$Floor }
    }

    # Construction des noms

    $MailboxName = "MeetingRoom-$Country-$City-$RoomName"
    $Alias       = "MR-$Country-$City-$RoomName"

    $MailboxName = $MailboxName.Replace(" ","")
    $Alias       = $Alias.Replace(" ","")

    $PrimarySMTP = "$Alias@$Domain"

    # Vérification existence

    $Existing = Get-Mailbox `
        -Identity $Alias `
        -ErrorAction SilentlyContinue

    if ($Existing)
    {
        [System.Windows.Forms.MessageBox]::Show(
            "La salle existe déjà."
        )
        return
    }

    # Equipements

    $Equipment = @()

    $VideoDeviceName   = $null
    $DisplayDeviceName = $null

    if ($chkVisio.Checked)
    {
        $Equipment += "VisioConference"
        $VideoDeviceName = "VisioConference"
    }

    if ($chkProjector.Checked)
    {
        $Equipment += "VideoProjector"

        if (-not $DisplayDeviceName)
        {
            $DisplayDeviceName = "VideoProjector"
        }
    }

    if ($chkTV.Checked)
    {
        $Equipment += "TVScreen"
        $DisplayDeviceName = "TvScreen"
    }

    try
    {
        #################################################################
        # Création de la Room Mailbox
        #################################################################

        New-Mailbox `
            -Room `
            -Name $MailboxName `
            -Alias $Alias `
            -PrimarySmtpAddress $PrimarySMTP

        #################################################################
        # Attente réplication Exchange Online
        #################################################################

        $Retry = 0

        do
        {
            Start-Sleep -Seconds 10

            $RoomCreated = Get-Mailbox `
            -Identity $PrimarySMTP `
            -ErrorAction SilentlyContinue

        $Retry++

    }
    until (($RoomCreated) -or ($Retry -ge 30))

    if(-not $RoomCreated)
    {
        throw "La boîte aux lettres n'est pas encore répliquée dans Exchange Online."
    }

        #################################################################
        # Place
        #################################################################

        Set-Place `
            -Identity $PrimarySMTP `
            -Capacity $Capacity `
            -Building $Building `
            -Floor $FloorNumber `
            -City $City `
            -CountryOrRegion $Country `
            -VideoDeviceName $VideoDeviceName `
            -DisplayDeviceName $DisplayDeviceName

        #################################################################
        # AutoAccept
        #################################################################

        Set-CalendarProcessing `
            -Identity $PrimarySMTP `
            -AutomateProcessing AutoAccept `
            -BookingWindowInDays 365 `
            -MaximumDurationInMinutes 10080 `
            -DeleteSubject $false `
            -AddOrganizerToSubject $false `
            -ProcessExternalMeetingMessages $false 

        #################################################################
        # Equipements complémentaires
        #################################################################

        if ($Equipment.Count -gt 0)
        {
            Set-Mailbox `
                -Identity $PrimarySMTP `
                -ResourceCustom $Equipment
        }

        #################################################################
        # Rafraîchissement
        #################################################################

        Refresh-AllRooms

        [System.Windows.Forms.MessageBox]::Show(
            "Salle créée avec succès.`n`nNom : $MailboxName`nSMTP : $PrimarySMTP"
        )
    }
    catch
    {
        [System.Windows.Forms.MessageBox]::Show(
            "Erreur : $($_.Exception.Message)"
        )
    }
}
function New-LectraRoomList {

    $RoomListName = $txtRoomList.Text.Trim()

    if([string]::IsNullOrWhiteSpace($RoomListName))
    {
        return
    }

    $Existing = Get-DistributionGroup `
        -Identity $RoomListName `
        -ErrorAction SilentlyContinue

    if($Existing)
    {
        [System.Windows.Forms.MessageBox]::Show(
            "La RoomList existe déjà."
        )
        return
    }

    New-DistributionGroup `
        -Name $RoomListName `
        -RoomList

    Refresh-RoomLists

    [System.Windows.Forms.MessageBox]::Show(
        "RoomList créée."
    )
}

