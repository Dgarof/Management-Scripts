    foreach($RL in $RoomLists)
    {
        # $cmbRoomList.Items.Add($RL.Name)
        [void]$cmbRoomList.Items.Add($RL.Name)
    }
}
function Search-Rooms {

    $lstRooms.Items.Clear()

    $Text = $txtSearch.Text.Trim()

    $Rooms = $Global:AllRooms

    if ($Text)
    {
        $Rooms = $Rooms | Where-Object {
            $_.DisplayName -like "*$Text*" -or
            $_.Alias -like "*$Text*"
        }
    }

    foreach($Room in $Rooms)
    {
        # $lstRooms.Items.Add($Room.DisplayName)
        [void]$lstRooms.Items.Add($Room.DisplayName)
    }
}
function Load-RoomListMembers {

